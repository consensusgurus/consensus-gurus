// Generator for SoT admin geo maps: base world map (Natural Earth 1 projection)
// + compact city/region/country coordinate index for locating players.
const fs = require('fs');
const topojson = require('topojson-client');
const d3 = require('d3-geo');
const cities = require('all-the-cities');

const W = 980, H = 520, PAD = 6;

// ---------- 1) Base world map ----------
function buildWorld(res) {
  const topo = JSON.parse(fs.readFileSync(`node_modules/world-atlas/countries-${res}.json`, 'utf8'));
  const fc = topojson.feature(topo, topo.objects.countries);
  const proj = d3.geoNaturalEarth1().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], { type: 'Sphere' });
  const path = d3.geoPath(proj).digits(1);
  const countries = fc.features
    .map((f) => ({ n: (f.properties && f.properties.name) || '', d: path(f) }))
    .filter((c) => c.d);
  const sphere = path({ type: 'Sphere' });
  const k = proj.scale();
  const [tx, ty] = proj.translate();
  // Verify a hand-rolled NE1 projection matches d3 exactly (it must, since the
  // committed lib re-implements it to avoid a runtime d3 dependency).
  const ne1 = (lonDeg, latDeg) => {
    const lam = (lonDeg * Math.PI) / 180;
    const phi = (latDeg * Math.PI) / 180;
    const p2 = phi * phi, p4 = p2 * p2;
    const x = lam * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
    const y = phi * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
    return [tx + k * x, ty - k * y];
  };
  const samples = [[0, 0], [-97.74, 30.27], [2.35, 48.86], [151.21, -33.87], [-157.86, 21.31], [18.42, -33.92]];
  let maxErr = 0;
  const vectors = samples.map(([lon, lat]) => {
    const a = proj([lon, lat]);
    const b = ne1(lon, lat);
    maxErr = Math.max(maxErr, Math.abs(a[0] - b[0]), Math.abs(a[1] - b[1]));
    return { lon, lat, x: +a[0].toFixed(3), y: +a[1].toFixed(3) };
  });
  if (maxErr > 0.01) throw new Error('NE1 reimplementation mismatch: ' + maxErr);
  return { res, countries, sphere, k, tx, ty, vectors };
}

const w110 = buildWorld('110m');
const w50 = buildWorld('50m');
function emitWorld(w) {
  const body = `// AUTO-GENERATED by scripts/generate-admin-geo.js. Do not hand-edit.
// World basemap for the admin player-location maps. Source: world-atlas ${w.res}
// (Natural Earth), projected with geoNaturalEarth1 fit to ${W}x${H} (pad ${PAD}).
// PROJ = { k, tx, ty } are the fitted projection constants; lib/geo-locate.js
// re-implements the NE1 forward formula against them (verified at generation
// time to <0.01px against d3-geo). TEST_VECTORS are spot checks for smoke tests.
export const WORLD = {
  width: ${W},
  height: ${H},
  k: ${w.k},
  tx: ${w.tx},
  ty: ${w.ty},
  sphere: ${JSON.stringify(w.sphere)},
  countries: ${JSON.stringify(w.countries)},
};
export const TEST_VECTORS = ${JSON.stringify(w.vectors)};
`;
  return body;
}
const out110 = emitWorld(w110);
const out50 = emitWorld(w50);
fs.mkdirSync('out', { recursive: true });
fs.writeFileSync('out/admin-world-map-110m.js', out110);
fs.writeFileSync('out/admin-world-map-50m.js', out50);
console.log('world 110m KB', Math.round(out110.length / 1024), '| 50m KB', Math.round(out50.length / 1024));

// ---------- 2) City index ----------
// GeoNames admin1 codes are numeric for CA/AU; Vercel's x-vercel-ip-country-region
// sends ISO-3166-2 letters. Map the big four English-speaking geos; everywhere else
// region matching just falls back to population order.
const CA_ADMIN = { '01': 'AB', '02': 'BC', '03': 'MB', '04': 'NB', '05': 'NL', '07': 'NS', '08': 'ON', '09': 'PE', '10': 'QC', '11': 'SK', '12': 'YT', '13': 'NT', '14': 'NU' };
const AU_ADMIN = { '01': 'ACT', '02': 'NSW', '03': 'NT', '04': 'QLD', '05': 'SA', '06': 'TAS', '07': 'VIC', '08': 'WA' };
function isoAdmin(cc, code) {
  if (!code) return '';
  if (cc === 'CA') return CA_ADMIN[code] || code;
  if (cc === 'AU') return AU_ADMIN[code] || code;
  return code;
}
const norm = (s) => String(s || '')
  .normalize('NFD').replace(/[̀-ͯ]/g, '')
  .toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

const MIN_POP = 2000;
const byKey = new Map(); // "cc|norm" -> [{a, lat, lon, pop}]
const regionAgg = new Map(); // "cc|admin" -> {wLat, wLon, w}
const countryAgg = new Map(); // cc -> {wLat, wLon, w}
let kept = 0;
for (const c of cities) {
  const cc = c.country;
  if (!cc) continue;
  const [lon, lat] = c.loc.coordinates;
  const pop = c.population || 0;
  const a = isoAdmin(cc, c.adminCode);
  const wgt = Math.max(pop, 200);
  const rk = `${cc}|${a}`;
  const r = regionAgg.get(rk) || { wLat: 0, wLon: 0, w: 0 };
  r.wLat += lat * wgt; r.wLon += lon * wgt; r.w += wgt; regionAgg.set(rk, r);
  const cAgg = countryAgg.get(cc) || { wLat: 0, wLon: 0, w: 0 };
  cAgg.wLat += lat * wgt; cAgg.wLon += lon * wgt; cAgg.w += wgt; countryAgg.set(cc, cAgg);
  if (pop < MIN_POP) continue;
  kept++;
  const entry = { a, lat: +lat.toFixed(2), lon: +lon.toFixed(2), pop };
  const names = new Set([norm(c.name)]);
  if (c.altName) names.add(norm(c.altName));
  // st/saint spelling variants both ways
  for (const n of [...names]) {
    if (n.startsWith('st ')) names.add('saint ' + n.slice(3));
    else if (n.startsWith('saint ')) names.add('st ' + n.slice(6));
  }
  for (const n of names) {
    if (!n) continue;
    const key = `${cc}|${n}`;
    if (!byKey.has(key)) byKey.set(key, []);
    byKey.get(key).push(entry);
  }
}
// Manual aliases for common Vercel/MaxMind names that differ from GeoNames canon.
// The alias candidate goes FIRST even when smaller towns share the plain name
// (MaxMind's "Washington" means DC, not Washington UT).
const ALIASES = [
  ['US|new york', 'US|new york city'],
  ['US|washington', 'US|washington d c'],
];
for (const [from, to] of ALIASES) {
  const src = byKey.get(to);
  if (!src || !src.length) continue;
  const cur = byKey.get(from) || [];
  byKey.set(from, [src[0], ...cur.filter((e) => e !== src[0])]);
}
// Keep top 4 candidates per key by population.
let entries = 0;
const parts = [];
for (const [key, list] of [...byKey.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
  list.sort((x, y) => y.pop - x.pop);
  const top = list.slice(0, 4);
  entries += top.length;
  parts.push(key + '~' + top.map((e) => `${e.a},${e.lat},${e.lon}`).join('~'));
}
const cityData = parts.join(';');
const regions = {};
for (const [rk, r] of regionAgg) { if (rk.split('|')[1]) regions[rk] = [+(r.wLat / r.w).toFixed(2), +(r.wLon / r.w).toFixed(2)]; }
const countriesC = {};
for (const [cc, r] of countryAgg) countriesC[cc] = [+(r.wLat / r.w).toFixed(2), +(r.wLon / r.w).toFixed(2)];

const cityBody = `// AUTO-GENERATED by scripts/generate-admin-geo.js. Do not hand-edit.
// Compact coordinate index for locating players from Vercel edge-geo fields
// (country ISO2 + region subdivision + city name). Built from GeoNames via the
// all-the-cities package (cities with population >= ${MIN_POP}; ${kept} cities,
// ${entries} name entries incl. alt spellings). Format: one big string of
// "CC|normalizedname~admin,lat,lon~..." records joined by ";" — parsed lazily
// into a Map on first lookup (see lib/geo-locate.js). Candidates are ordered by
// population (largest first); admin codes are ISO-style for US/CA/AU/GB.
// REGION_CENTROIDS / COUNTRY_CENTROIDS are population-weighted city means, the
// fallback pins when a city can't be matched (keys "CC|ADMIN" / "CC").
export const CITY_DATA = ${JSON.stringify(cityData)};
export const REGION_CENTROIDS = ${JSON.stringify(regions)};
export const COUNTRY_CENTROIDS = ${JSON.stringify(countriesC)};
`;
fs.writeFileSync('out/geo-cities.js', cityBody);
console.log('cities kept', kept, 'entries', entries, 'geo-cities KB', Math.round(cityBody.length / 1024));
console.log('regions', Object.keys(regions).length, 'countries', Object.keys(countriesC).length);
