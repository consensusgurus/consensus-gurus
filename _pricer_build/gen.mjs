// swap siblings at every level: a bracket automorphism, preserves who-meets-whom
function scramble(arr){
  const n=arr.length; let out=arr.slice();
  for(let block=2;block<=n;block*=2){
    for(let i=0;i<n;i+=block){ if(rnd()<0.5){ const h=block/2; const l=out.slice(i,i+h),r=out.slice(i+h,i+block); out.splice(i,block,...r,...l);} }
  }
  return out;
}
