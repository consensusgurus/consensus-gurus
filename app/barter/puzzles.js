//     The trade budget is always par + 5; the client derives it, never stores it.
//   - Par bands: weekday 11-14, Sunday 20-25. At most 2 tiles (Sunday 4) may
//     start on their correct square, and no word may start already solved.
//   - Solution words come from the common band of the shared vocabulary
//     (app/warmer/vocab.js top 20,000) AND the site dictionary
