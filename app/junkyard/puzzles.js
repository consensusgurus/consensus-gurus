// Puzzle data for Junkyard: the same daily sliding-block jam as Parker and
// Impound, on the biggest lot the engine can hold.
//
// EIGHT BY EIGHT, EXIT ON ROW 4. Each block is [len, horiz, fixed, pos]:
//   len    2 or 3 squares long
//   horiz  1 if it slides left and right, 0 if up and down
//   fixed  the coordinate it can never change (its row if horizontal, its
//          column if vertical)
//   pos    where its top or left end sits along the axis it slides on
// Block 0 is always the RED one: two long, horizontal, on row 4, and it leaves
// through the gap in the right-hand wall on that row. Eight is EVEN, so there
// is no true middle rank and the lane has to lean: row 4 puts four ranks of
// traffic above it and three below, the opposite lean to Parker's row 2 on a
// 6x6, so the family's two even boards do not jam the same way.
//
//   par    the EXACT minimum number of moves, where one move is one block
//          sliding any distance. This is what the game calls PERFECT; the field
//          keeps Parker's name for it so the three banks have one shape, and
//          the softer target players are shown is derived from it in lib/par.js.
//          Not an estimate: found by breadth-first search over the whole
//          reachable state space in lib/jam-core.js, the same search the live
//          hint and scripts/verify-junkyard.mjs run.
//
// EIGHT BY EIGHT IS THE LAST RUNG THIS FAMILY CAN HAVE. lib/jam-core packs
// occupancy into two 32-bit words and the packed state key into three bits a
// position, so 64 cells and n <= 8 are both hard ceilings, and compile() throws
// rather than truncating. A fourth size is a different engine, not a bigger
// argument, which is why Junkyard's own copy calls it the biggest lot rather
// than merely a bigger one.
//
// THE WEEK CLIMBS IN TWO RUNGS, AND EVERY RUNG SITS ABOVE IMPOUND'S. Monday to
// Wednesday run 22 to 35, Thursday to Saturday 31 to 47, and the Sunday Edition
// 44 and up, against Impound's 16 to 25, 23 to 35 and 34 to 50. Monday alone
// already runs deeper than any Parker board short of a Sunday. Each rung also
// ramps inside itself, so Monday is the gentlest board of the week and Saturday
// the stiffest short of the Sunday. verify-junkyard.mjs checks the bands, the
// within-week ramp AND that every band beats the Impound band it corresponds
// to, because "the biggest game" is a claim the bank has to keep.
//
// WHY 8x8 WAS BANKABLE WHEN IT HAD BEEN MEASURED AS OUT OF REACH. The earlier
// finding (a 400-board sample that did not finish in ten minutes) was taken on
// RANDOM packings, and random 8x8 packings sprawl: over half exhaust a 40,000
// state cap, and half of those are still unresolved at six million states,
// twelve seconds apiece, because an unsolvable board has to exhaust its whole
// reachable component before it can be called unsolvable. The generator does
// not sample, it CLIMBS, and it climbs toward tightly jammed boards, which are
// deep AND narrow: only about 4% of the candidates it actually evaluates hit
// the cap, and it reaches par 54 in the wall clock that gets 7x7 to 38. The
// lesson is not that the old measurement was careless, it is that a random
// board is a bad guide to what a climb can reach.
//
// BANKED BY scripts/gen-jam.mjs, which takes the board size as an argument and
// serves all three games. Every board here was accepted only because the search
// reached the goal inside a 40,000-state cap, so re-solving the whole bank is
// cheap by construction. To extend:
//
//   node scripts/gen-jam.mjs --n=8 --exit=4 --from=<next day> --days=N \
//     --startnum=<last+1> --prefix=junkyard --game=Junkyard \
//     --windows='{"1":[22,28],"2":[25,32],"3":[28,35],"4":[31,39],"5":[34,43],"6":[37,47],"0":[44,80]}' \
//     --avoid=app/junkyard/puzzles.js,app/impound/puzzles.js,app/parker/puzzles.js \
//     --out=/tmp/tail.js
//
