// flag honest, and its par of 26 sits under the 28 of the Saturday after it so
// the week still climbs. The two boards that had sat behind it (2027-01-30 and
// 01-31) came off the end rather than leaving a hole at 01-29, because a hole
// makes `pickPuzzle` re-serve the previous day's board. Net cost: two days of
// runway out of 149.
//
// THE WEEK CLIMBS IN TWO RUNGS, AND EVERY RUNG SITS ABOVE PARKER'S. Monday to
// Wednesday run 16 to 25, Thursday to Saturday 23 to 35, and the Sunday Edition
// 38 to 52, against Parker's 11 to 14, 16 to 20 and 32 to 38. Each rung also
// ramps inside itself, so Monday is the gentlest board of the week and Saturday
// the stiffest short of the Sunday. verify-impound.mjs checks the bands, the
// within-week ramp AND that every band beats the Parker band it corresponds to,
// because "the bigger game" is a claim the bank has to keep.
//
