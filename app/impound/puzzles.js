// SEVEN BY SEVEN, EXIT ON ROW 3. Each block is [len, horiz, fixed, pos]:
//   len    2 or 3 squares long
//   horiz  1 if it slides left and right, 0 if up and down
//   fixed  the coordinate it can never change (its row if horizontal, its
//          column if vertical)
//   pos    where its top or left end sits along the axis it slides on
// Block 0 is always the RED one: two long, horizontal, on row 3, and it leaves
// through the gap in the right-hand wall on that row. Seven is odd, so row 3 is
// the true middle rank, with three ranks of traffic above it and three below.
//
//   par    the EXACT minimum number of moves, where one move is one block
//          sliding any distance. This is what the game calls PERFECT; the field
//          keeps Parker's name for it so the two banks have one shape, and the
//          softer target players are shown is derived from it in lib/par.js.
//          Not an estimate: found by breadth-first search over the whole
//          reachable state space in lib/jam-core.js, the same search the live
//          hint and scripts/verify-impound.mjs run.
//
